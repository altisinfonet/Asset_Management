-- Accessories are quantity-tracked: refuse a check-out that would exceed qty_total.
CREATE FUNCTION app.assignment_check_accessory_stock() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
DECLARE
  v_total integer;
  v_out   integer;
BEGIN
  SELECT a.qty_total INTO v_total
    FROM app.accessory a
   WHERE a.tenant_id = NEW.tenant_id AND a.id = NEW.accessory_id
     FOR UPDATE;                                           -- serialises concurrent check-outs
  SELECT COALESCE(sum(s.quantity - s.quantity_returned), 0) INTO v_out
    FROM app.assignment s
   WHERE s.tenant_id = NEW.tenant_id AND s.accessory_id = NEW.accessory_id AND s.checked_in_at IS NULL;
  IF v_out + NEW.quantity > v_total THEN
    RAISE EXCEPTION 'insufficient accessory stock: % available, % requested', v_total - v_out, NEW.quantity
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER assignment_accessory_stock BEFORE INSERT ON app.assignment
  FOR EACH ROW WHEN (NEW.accessory_id IS NOT NULL AND NEW.checked_in_at IS NULL)
  EXECUTE FUNCTION app.assignment_check_accessory_stock();

-- Returns only move forward: quantity is fixed after check-out and quantity_returned never
-- decreases (so a closed custody period cannot be reopened).
CREATE FUNCTION app.assignment_guard_update() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF NEW.quantity <> OLD.quantity THEN
    RAISE EXCEPTION 'assignment quantity cannot change after check-out' USING ERRCODE = 'check_violation';
  END IF;
  IF NEW.quantity_returned < OLD.quantity_returned THEN
    RAISE EXCEPTION 'quantity_returned cannot decrease (% -> %)', OLD.quantity_returned, NEW.quantity_returned
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER assignment_b_guard_update BEFORE UPDATE OF quantity, quantity_returned ON app.assignment
  FOR EACH ROW EXECUTE FUNCTION app.assignment_guard_update();

