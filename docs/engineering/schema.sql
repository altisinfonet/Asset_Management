  FOR r IN SELECT unnest(ARRAY['asset','location','person','accessory','consumable']) AS relname LOOP
    EXECUTE format('CREATE TRIGGER %I BEFORE INSERT ON app.%I FOR EACH ROW EXECUTE FUNCTION app.fill_default_company()',
                   'trg_company_' || r.relname, r.relname);
  END LOOP;
END
$$;

-- RLS: the policy is generated from the catalog so no tenant table can be forgotten.
-- (partitions are excluded here; ensure_partitions covers them)
DO $$
DECLARE
  r record;
  v_guard constant text := '(SELECT NULLIF(current_setting(''app.tenant_id'', true), '''')::uuid)';
BEGIN
  FOR r IN
    SELECT c.relname
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      JOIN pg_attribute a ON a.attrelid = c.oid AND a.attname = 'tenant_id' AND NOT a.attisdropped
     WHERE n.nspname = 'app' AND c.relkind IN ('r','p') AND NOT c.relispartition
  LOOP
    EXECUTE format('ALTER TABLE app.%I ENABLE ROW LEVEL SECURITY', r.relname);
    EXECUTE format('ALTER TABLE app.%I FORCE ROW LEVEL SECURITY', r.relname);
    EXECUTE format('CREATE POLICY tenant_isolation ON app.%I USING (tenant_id = %s) WITH CHECK (tenant_id = %s)',
                   r.relname, v_guard, v_guard);
  END LOOP;
END
$$;

