  r record;
BEGIN
  -- version/updated_at bump on every table that carries a version column
  FOR r IN
    SELECT c.relname
      FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      JOIN pg_attribute a ON a.attrelid = c.oid AND a.attname = 'version' AND NOT a.attisdropped
     WHERE n.nspname = 'app' AND c.relkind = 'r'
  LOOP
    EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON app.%I FOR EACH ROW EXECUTE FUNCTION app.touch_row()',
                   'trg_touch_' || r.relname, r.relname);
  END LOOP;

