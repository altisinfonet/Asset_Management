-- =============================================================================
-- Asset Tracker: PostgreSQL 16 / 17 / 18 schema for milestones M1 + M2
-- Source of truth for docs/engineering/data_model.md. Runnable with psql:
--
--   psql -v ON_ERROR_STOP=1 -U postgres -d <db> -f schema.sql
--
-- Run it ONCE as a superuser (or a role with CREATEROLE + CREATE on the db):
-- Part A bootstraps roles, schemas and extensions; then the script switches to
-- the owner role (SET ROLE app_owner) and Part B creates every object as
-- app_owner, so app_user never owns anything. Passwords/LOGIN credentials are
-- NOT set here (set them out of band: ALTER ROLE app_user PASSWORD '...').
--
-- Conventions (see data_model.md section 2):
--   * every tenant table has tenant_id uuid NOT NULL + UNIQUE (tenant_id, id)
--     and composite FKs (tenant_id, x_id) -> parent (tenant_id, id)
--   * ids are UUIDv7 generated by the APPLICATION. There are NO database-side id defaults
--     (uuidv7() is PostgreSQL 18 only; the self-hosted edition supports BYO PostgreSQL 16/17;
--     decision ED-08). Every INSERT must supply id; app.provision_tenant seeds its rows with
--     gen_random_uuid() (PostgreSQL 13+). app.schema_lint() fails if a uuidv7() default reappears.
--   * PostgreSQL version floor: 16. Features used: NULLS NOT DISTINCT (15), security_invoker
--     views (15), gen_random_uuid() (13), declarative partitioning with partitioned-table FKs
--     (12), array slices with omitted bounds (9.6). Nothing here is PostgreSQL 18 specific;
--     tested on 16, 17 and 18 (data_model.md section 10).
--   * audit_log and asset_history are range-partitioned by month on "at" (decision ED-09)
--   * RLS: ENABLE + FORCE on every table that has tenant_id, one policy
--     "tenant_isolation" with the NULLIF form in USING and WITH CHECK
--   * no SECURITY DEFINER anywhere, views are security_invoker
--   * app_user gets grants on partitioned PARENTS only, never on partitions
--   * [M1] / [M2] tags in comments mark the milestone of each object
-- =============================================================================

\set ON_ERROR_STOP on

-- =============================================================================
-- PART A. Bootstrap (superuser / admin)
-- =============================================================================

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_owner') THEN
    -- owner + migrator: owns every object, runs migrations. Plain role:
    -- not superuser, no BYPASSRLS, so FORCE RLS binds it (backfills must set the tenant).
    CREATE ROLE app_owner LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_user') THEN
    -- runtime role used by api/worker/scheduler (through PgBouncer): not owner, no BYPASSRLS.
    CREATE ROLE app_user LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION NOINHERIT;
  END IF;
END
$$;

DO $$
BEGIN
  EXECUTE format('REVOKE ALL ON DATABASE %I FROM PUBLIC', current_database());
  EXECUTE format('GRANT CONNECT ON DATABASE %I TO app_owner, app_user', current_database());
END
$$;

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO app_owner, app_user;   -- extension operators/functions live here

CREATE EXTENSION IF NOT EXISTS pg_trgm   SCHEMA public;  -- fuzzy search on tag/serial/name
CREATE EXTENSION IF NOT EXISTS btree_gin SCHEMA public;  -- lets GIN indexes lead with tenant_id

CREATE SCHEMA IF NOT EXISTS app      AUTHORIZATION app_owner;   -- tenant data, RLS
CREATE SCHEMA IF NOT EXISTS identity AUTHORIZATION app_owner;   -- pre-auth lookups, NO RLS (hashes + ids only)
REVOKE ALL ON SCHEMA app, identity FROM PUBLIC;
GRANT USAGE ON SCHEMA app, identity TO app_user;

ALTER ROLE app_user SET search_path = app, identity, public;
ALTER ROLE app_owner SET search_path = app, identity, public;

-- =============================================================================
-- PART B. Objects (owned by app_owner)
-- =============================================================================

SET ROLE app_owner;
SET search_path = app, identity, public;

