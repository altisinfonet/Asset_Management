// @ts-check
/**
 * Generates the design-token artefacts from docs/design/tokens.json (W3C Design Tokens format).
 *
 *   src/generated/tokens.ts           typed object (web and React Native)
 *   src/generated/tokens.css          CSS custom properties; light by default, dark via
 *                                     prefers-color-scheme and [data-theme="dark"]
 *   src/generated/tailwind-theme.css  Tailwind v4 `@theme` block (static, light defaults)
 *
 * Run with `pnpm --filter @assettracker/ui-tokens generate`. `pnpm build` runs it too, and the unit
 * test fails when the committed output is out of date with tokens.json.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER =
  'GENERATED by packages/ui-tokens/scripts/generate.mjs from docs/design/tokens.json. Do not edit.';

/** @param {unknown} node */
function isLeaf(node) {
  return typeof node === 'object' && node !== null && '$value' in node;
}

/**
 * Collect leaves below `node` as `[path[], leaf]`, skipping `$` metadata keys.
 * @param {Record<string, any>} node
 * @param {string[]} [prefix]
 * @returns {Array<[string[], any]>}
 */
export function leaves(node, prefix = []) {
  /** @type {Array<[string[], any]>} */
  const out = [];
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (isLeaf(child)) out.push([[...prefix, key], child]);
    else if (typeof child === 'object' && child !== null)
      out.push(...leaves(child, [...prefix, key]));
  }
  return out;
}

/** `12px` to 12, `100ms` to 100. */
function toNumber(/** @type {string | number} */ v) {
  if (typeof v === 'number') return v;
  const n = Number.parseFloat(v);
  if (Number.isNaN(n))
    throw new Error(`Cannot convert token value ${JSON.stringify(v)} to a number`);
  return n;
}

/** CSS variable name for a colour token path: `primary.solid` is `primary`, `primary.hover` is `primary-hover`. */
export function colorVarName(/** @type {string[]} */ p) {
  const [head, sub] = p;
  if (p.length === 1) return /** @type {string} */ (head);
  return sub === 'solid' ? `${head}` : `${head}-${sub}`;
}

/** @param {{ offsetX: string, offsetY: string, blur: string, spread: string, color: string }} s */
function shadowToCss(s) {
  return `${s.offsetX} ${s.offsetY} ${s.blur} ${s.spread} ${s.color}`;
}

/**
 * Build the structured token model used by every output.
 * @param {Record<string, any>} json parsed tokens.json
 */
export function buildModel(json) {
  /** @param {'light' | 'dark'} mode */
  const colorMode = (mode) => {
    /** @type {Record<string, string>} */
    const flat = {};
    /** @type {Record<string, any>} */
    const nested = {};
    for (const [p, leaf] of leaves(json.color[mode])) {
      flat[colorVarName(p)] = leaf.$value;
      /** @type {Record<string, any>} */
      let cursor = nested;
      p.slice(0, -1).forEach((k) => (cursor = cursor[k] ??= {}));
      cursor[/** @type {string} */ (p.at(-1))] = leaf.$value;
    }
    return { flat, nested };
  };
  const light = colorMode('light');
  const dark = colorMode('dark');

  /** @param {Record<string, any>} group @param {(v: any) => any} map */
  const mapGroup = (group, map) =>
    Object.fromEntries(leaves(group).map(([p, leaf]) => [p.join('.'), map(leaf.$value)]));

  const shadow = {
    light: mapGroup(json.shadow.light, (v) => v),
    dark: mapGroup(json.shadow.dark, (v) => v),
  };

  return {
    color: { light: light.nested, dark: dark.nested },
    colorFlat: { light: light.flat, dark: dark.flat },
    font: {
      family: mapGroup(json.font.family, (v) => v),
      weight: mapGroup(json.font.weight, (v) => v),
      size: mapGroup(json.font.size, toNumber),
      lineHeight: mapGroup(json.font.lineHeight, toNumber),
    },
    space: mapGroup(json.space, toNumber),
    size: mapGroup(json.size, toNumber),
    radius: mapGroup(json.radius, toNumber),
    shadow,
    duration: mapGroup(json.duration, toNumber),
    breakpoint: mapGroup(json.breakpoint, toNumber),
    zIndex: mapGroup(json.zIndex, (v) => v),
  };
}

/** @param {ReturnType<typeof buildModel>} m */
function renderTs(m) {
  const { colorFlat: _flat, ...tokens } = m;
  return `// ${HEADER}
/** Design tokens. Dimensions are plain numbers (px, ms) so React Native can use them directly. */
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

/** Flat colour maps keyed by CSS variable name (without the \`--color-\` prefix). */
export const colorVars = ${JSON.stringify(m.colorFlat, null, 2)} as const;

export type Tokens = typeof tokens;
export type ThemeName = 'light' | 'dark';
export type ColorName = keyof (typeof colorVars)['light'];
export type ThemeColors = (typeof tokens)['color'][ThemeName];
`;
}

/** @param {Record<string, string>} flat @param {string} indent */
function colorDecls(flat, indent) {
  return Object.entries(flat)
    .map(([name, value]) => `${indent}--color-${name}: ${value};`)
    .join('\n');
}

/** @param {Record<string, any>} shadows @param {string} indent */
function shadowDecls(shadows, indent) {
  return Object.entries(shadows)
    .map(([name, v]) => `${indent}--shadow-${name}: ${shadowToCss(v)};`)
    .join('\n');
}

/** @param {ReturnType<typeof buildModel>} m */
function renderCss(m) {
  const px = (/** @type {number} */ n) => `${n}px`;
  const statics = [
    ...Object.entries(m.space).map(([k, v]) => `  --space-${k.replace('.', '_')}: ${px(v)};`),
    ...Object.entries(m.size).map(([k, v]) => `  --size-${k}: ${px(v)};`),
    ...Object.entries(m.radius).map(([k, v]) => `  --radius-${k}: ${px(v)};`),
    ...Object.entries(m.duration).map(([k, v]) => `  --duration-${k}: ${v}ms;`),
    ...Object.entries(m.zIndex).map(([k, v]) => `  --z-${k}: ${v};`),
    ...Object.entries(m.font.size).map(
      ([k, v]) =>
        `  --font-size-${k}: ${px(v)};\n  --line-height-${k}: ${px(m.font.lineHeight[k] ?? 0)};`,
    ),
    ...Object.entries(m.font.weight).map(([k, v]) => `  --font-weight-${k}: ${v};`),
    `  --font-family-sans: ${m.font.family.sans.join(', ')};`,
    `  --font-family-mono: ${m.font.family.mono.join(', ')};`,
  ].join('\n');

  const darkBody = `${colorDecls(m.colorFlat.dark, '    ')}\n${shadowDecls(m.shadow.dark, '    ')}`;
  const darkBodyTop = `${colorDecls(m.colorFlat.dark, '  ')}\n${shadowDecls(m.shadow.dark, '  ')}`;

  return `/* ${HEADER}
 *
 * Theme selection: light by default; dark when the OS prefers it, unless the user forced light with
 * <html data-theme="light">; <html data-theme="dark"> forces dark. */

:root,
:root[data-theme='light'] {
  color-scheme: light;
${colorDecls(m.colorFlat.light, '  ')}
${shadowDecls(m.shadow.light, '  ')}
${statics}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${darkBody}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${darkBodyTop}
}
`;
}

/** @param {ReturnType<typeof buildModel>} m */
function renderTailwind(m) {
  const px = (/** @type {number} */ n) => `${n}px`;
  const lines = [
    '  /* Wipe Tailwind defaults for the namespaces the design system owns; components use semantic tokens only. */',
    '  --color-*: initial;',
    '  --radius-*: initial;',
    '  --shadow-*: initial;',
    '  --text-*: initial;',
    '  --breakpoint-*: initial;',
    '',
    `  --font-sans: ${m.font.family.sans.join(', ')};`,
    `  --font-mono: ${m.font.family.mono.join(', ')};`,
    '  --spacing: 4px;',
    '',
    ...Object.entries(m.font.size).flatMap(([k, v]) => [
      `  --text-${k}: ${px(v)};`,
      `  --text-${k}--line-height: ${px(m.font.lineHeight[k] ?? 0)};`,
    ]),
    '',
    ...Object.entries(m.radius).map(([k, v]) => `  --radius-${k}: ${px(v)};`),
    '',
    ...Object.entries(m.breakpoint).map(([k, v]) => `  --breakpoint-${k}: ${px(v)};`),
    '',
    '  /* Light values; tokens.css overrides them for dark (unlayered CSS beats the theme layer). */',
    colorDecls(m.colorFlat.light, '  '),
    shadowDecls(m.shadow.light, '  '),
  ];
  return `/* ${HEADER} */\n\n@theme static {\n${lines.join('\n')}\n}\n`;
}

/**
 * @param {Record<string, any>} json
 * @returns {Record<string, string>} file name to content
 */
export function generate(json) {
  const model = buildModel(json);
  return {
    'tokens.ts': renderTs(model),
    'tokens.css': renderCss(model),
    'tailwind-theme.css': renderTailwind(model),
  };
}

export const defaultTokensPath = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../../../docs/design/tokens.json',
);

export function readTokens(/** @type {string} */ file = defaultTokensPath) {
  return JSON.parse(readFileSync(file, 'utf8'));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/generated');
  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of Object.entries(generate(readTokens()))) {
    writeFileSync(path.join(outDir, name), content);
    console.log(`wrote src/generated/${name}`);
  }
}
